"""Run every test suite against the running stack and write docs/test-report.md.

Prerequisites: `docker compose up -d --build --wait`, `uv sync`, and in frontend/: `npm ci` and
`npx playwright install chromium`.

Usage: uv run python scripts/run_e2e.py [--repeat-e2e N]
Exit code is non-zero if any suite fails. JUnit XML files are written to reports/.
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import platform
import shutil
import subprocess
import sys
import time
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "reports"
NPX = shutil.which("npx") or "npx"


def run(name: str, cmd: list[str], cwd: Path, junit: Path, env: dict | None = None) -> dict:
    print(f"\n=== {name}\n$ {' '.join(cmd)}", flush=True)
    start = time.time()
    proc = subprocess.run(cmd, cwd=cwd, env={**os.environ, **(env or {})})
    took = time.time() - start
    counts = parse_junit(junit) if junit.exists() else {"tests": 0, "failures": 0, "errors": 0, "skipped": 0}
    # Report a portable command line (no machine-specific paths).
    shown = " ".join(cmd).replace(sys.executable, "python").replace(NPX, "npx").replace(str(ROOT) + os.sep, "")
    return {"name": name, "command": shown, "exit": proc.returncode, "seconds": took, **counts}


def parse_junit(path: Path) -> dict:
    root = ET.parse(path).getroot()
    suites = [root] if root.tag == "testsuite" else list(root.iter("testsuite"))
    total = {"tests": 0, "failures": 0, "errors": 0, "skipped": 0}
    for s in suites:
        for k in total:
            total[k] += int(s.get(k, 0) or 0)
    return total


def version(cmd: list[str]) -> str:
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=30).stdout.strip().splitlines()[0]
    except Exception:
        return "unavailable"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repeat-e2e", type=int, default=2, help="repeat each browser test N times")
    args = parser.parse_args()
    REPORTS.mkdir(exist_ok=True)
    py = [sys.executable, "-m", "pytest", "-q", "-p", "no:warnings"]
    results = [
        run("Unit, in-process API and static security tests", py + [f"--junitxml={REPORTS / 'unit.xml'}"],
            ROOT, REPORTS / "unit.xml"),
        run("Live stack: API, isolation, PSI-CA, release gating, leak scan", py + ["-m", "live",
            f"--junitxml={REPORTS / 'live.xml'}"], ROOT, REPORTS / "live.xml"),
        run(f"Browser end-to-end (Playwright, each test x{args.repeat_e2e})",
            [NPX, "playwright", "test", f"--repeat-each={args.repeat_e2e}", "--reporter=list,junit"],
            ROOT / "frontend", REPORTS / "e2e.xml", env={"PLAYWRIGHT_JUNIT_OUTPUT_NAME": str(REPORTS / "e2e.xml")}),
    ]
    write_report(results, args.repeat_e2e)
    failed = [r for r in results if r["exit"] != 0 or r["failures"] or r["errors"]]
    print("\nReport written to docs/test-report.md;", "FAILED" if failed else "all suites passed")
    return 1 if failed else 0


def write_report(results: list[dict], repeat: int) -> None:
    commit = version(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"])
    dirty = bool(subprocess.run(["git", "-C", str(ROOT), "status", "--porcelain"], capture_output=True,
                                text=True).stdout.strip())
    lines = [
        "# Test report",
        "",
        f"Generated by `scripts/run_e2e.py` on {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M UTC} "
        f"for commit `{commit}`{' (with uncommitted changes)' if dirty else ''}.",
        "",
        "| Suite | Tests | Failures | Errors | Skipped | Duration | Result |",
        "|---|---:|---:|---:|---:|---:|---|",
    ]
    for r in results:
        ok = r["exit"] == 0 and not r["failures"] and not r["errors"]
        lines.append(f"| {r['name']} | {r['tests']} | {r['failures']} | {r['errors']} | {r['skipped']} | "
                     f"{r['seconds']:.0f} s | {'pass' if ok else '**FAIL**'} |")
    total = sum(r["tests"] for r in results)
    lines += [
        f"| **Total** | **{total}** | | | | | |",
        "",
        "## Commands",
        "",
        *[f"- {r['name']}: `{r['command']}`" for r in results],
        "",
        f"The browser suite runs every test {repeat} times to check that results repeat.",
        "",
        "## Environment",
        "",
        f"- OS: {platform.platform()}",
        f"- Python: {platform.python_version()}",
        f"- Node: {version(['node', '--version'])}",
        f"- Docker: {version(['docker', '--version'])}",
        f"- Docker Compose: {version(['docker', 'compose', 'version', '--short'])}",
        "",
        "## What the suites cover",
        "",
        "- **Unit, in-process and static:**",
        "  - fixture integrity and determinism;",
        "  - signing, binding and replay rules for tokens, tickets and result packages;",
        "  - agent set extraction against ground truth, local policy and contradiction labels;",
        "  - registry identity, channels, requests, quotas and release logic, with simulated agents;",
        "  - that migrations match the models;",
        "  - the compose isolation topology.",
        "- **Live stack:**",
        "  - health checks and the network and volume isolation of every container;",
        "  - Postgres row-lock races;",
        "  - exact PSI-CA counts equal to ground truth for all 6 persona pairs, with released bands matching;",
        "  - revoke-during-compute and expiry;",
        "  - service-authentication probes;",
        "  - owner-only My KG;",
        "  - the leak scan: every private identifier, its SHA-256 and its base64 form, searched across all",
        "    captured agent payloads, the registry database dump and all logs.",
        "- **Browser:**",
        "  - journeys A and B;",
        "  - the full four-researcher scenario: pause, tightening, +24 h expiry, the targeted flow and",
        "    cross-account leakage probes;",
        "  - My KG and Persona E, each researcher in an isolated browser context.",
        "",
    ]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "test-report.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    raise SystemExit(main())
